import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';

const publicationTitle =
  'Steroid receptor coactivator-1 enhances the stemness of glioblastoma by activating long noncoding RNA XIST/miR-152/KLF4 pathway';

test('delivers the real ScholarGraph discovery flow', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');

  await expect(page.getByRole('heading', { level: 1, name: '从一个学者、成果或学术主题开始' })).toBeVisible();
  await expect(page.getByRole('link', { name: '学者目录', exact: true }).first()).toBeVisible();
  await expect(page.getByRole('link', { name: '科研成果', exact: true }).first()).toBeVisible();
  await expect(page.getByRole('link', { name: '机构与学科', exact: true }).first()).toBeVisible();
  const accessibility = await new AxeBuilder({ page }).include('main').analyze();
  expect(accessibility.violations).toEqual([]);

  await page.goto('/graph-analytics');
  await expect(page.getByRole('heading', { level: 1, name: '图谱分析' })).toBeVisible();
  await expect(page.getByText('HugeGraph 图谱投影已启用')).toBeVisible();
  await page.getByRole('tab', { name: '人员合作' }).click();
  const analyticsGraph = page.getByLabel('可拖拽的合作关系图').first();
  const analyticsEnvelope = analyticsGraph.locator('ellipse[data-cluster-envelope="true"]').first();
  const analyticsClusterId = await analyticsEnvelope.getAttribute('data-cluster-id');
  if (analyticsClusterId === null) throw new Error('合作图簇没有可拖拽标识');
  const clusteredNode = analyticsGraph.locator(`g[data-analysis-node="true"].cluster-${analyticsClusterId}`).first();
  const clusteredNodeBefore = await clusteredNode.getAttribute('transform');
  const analyticsClusterHandle = analyticsGraph.locator(`[data-cluster-handle="true"][data-cluster-id="${analyticsClusterId}"]`);
  await analyticsClusterHandle.scrollIntoViewIfNeeded();
  const envelopeBounds = await analyticsClusterHandle.boundingBox();
  if (!envelopeBounds) throw new Error('合作图簇没有可拖拽区域');
  await page.mouse.move(envelopeBounds.x + envelopeBounds.width / 2, envelopeBounds.y + envelopeBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(envelopeBounds.x + envelopeBounds.width / 2 + 30, envelopeBounds.y + envelopeBounds.height / 2 + 18);
  await page.mouse.up();
  expect(await clusteredNode.getAttribute('transform')).not.toBe(clusteredNodeBefore);
  const analyticsNode = analyticsGraph.locator('g[data-analysis-node="true"]').first();
  await analyticsNode.scrollIntoViewIfNeeded();
  const analyticsBefore = await analyticsNode.getAttribute('transform');
  const analyticsBounds = await analyticsNode.locator('circle').boundingBox();
  if (!analyticsBounds) throw new Error('人员合作节点没有可拖拽区域');
  await page.mouse.move(analyticsBounds.x + analyticsBounds.width / 2, analyticsBounds.y + analyticsBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(analyticsBounds.x + analyticsBounds.width / 2 + 45, analyticsBounds.y + analyticsBounds.height / 2 + 25);
  await page.mouse.up();
  expect(await analyticsNode.getAttribute('transform')).not.toBe(analyticsBefore);
  const analyticsShell = analyticsGraph.locator('xpath=..').locator('xpath=..');
  const analyticsSelectedName = (await analyticsShell.locator('.sg-collaboration-detail h3').first().textContent())?.trim();
  if (!analyticsSelectedName) throw new Error('合作图选中节点没有详情名称');
  await analyticsShell.getByRole('button', { name: '查看关系来源' }).click();
  await expect(page.getByRole('dialog', { name: `${analyticsSelectedName}的关系来源` })).toBeVisible();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await analyticsShell.getByRole('button', { name: '从当前图中移除' }).click();
  await page.getByRole('button', { name: '从当前视图移除' }).click();
  await expect(analyticsShell.getByRole('button', { name: '恢复已移除节点（1）' })).toBeVisible();
  await analyticsShell.getByRole('button', { name: '恢复已移除节点（1）' }).click();
  await analyticsShell.getByRole('button', { name: '放大图谱区域' }).click();
  await expect(page.getByRole('dialog', { name: '合作关系图放大视图' })).toBeVisible();
  await page.keyboard.press('Escape');

  await page.goto('/scholars');
  await expect(page.getByRole('heading', { level: 1, name: '学者目录' })).toBeVisible();
  await page.getByRole('searchbox', { name: '搜索学者目录' }).fill('丁俊莹');
  const scholarRow = page.getByRole('row', { name: /丁俊莹/ });
  await expect(scholarRow).toBeVisible();
  await scholarRow.click();
  await expect(page.getByRole('heading', { level: 1, name: '丁俊莹' })).toBeVisible();
  await expect(page.getByText('Dalian University of Technology').first()).toBeVisible();
  await page.getByRole('tab', { name: /关系网络/ }).click();
  await expect(page.getByRole('heading', { level: 2, name: '学术关系网络' })).toBeVisible();
  await expect(page.getByText('关系图服务正常')).toBeVisible();
  const scholarGraph = page.getByLabel('可拖拽的交互关系图');
  const graphBounds = await scholarGraph.boundingBox();
  if (!graphBounds) throw new Error('学者关系图没有可交互区域');
  await page.mouse.move(graphBounds.x + 40, graphBounds.y + 40);
  await page.mouse.down();
  await page.mouse.move(graphBounds.x + 100, graphBounds.y + 75);
  await page.mouse.up();
  await expect(scholarGraph.locator('.sg-network-surface')).toHaveAttribute('style', /translate3d\(60px, 35px, 0px\)/);
  await page.getByRole('button', { name: '重置图谱位置' }).click();
  const expandableNode = scholarGraph.locator('g[data-graph-node="true"]:not(.root)').first();
  await expandableNode.click();
  await page.getByRole('button', { name: '展开一度关系' }).click();
  await expect(page.getByRole('button', { name: '已展开一度关系' })).toBeVisible();
  await page.getByRole('button', { name: '放大图谱区域' }).click();
  await expect(page.getByRole('dialog', { name: '学术关系网络放大视图' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog', { name: '学术关系网络放大视图' })).toBeHidden();

  await page.goto('/outputs');
  await expect(page.getByRole('heading', { level: 1, name: '科研成果' })).toBeVisible();
  await page.getByRole('searchbox', { name: '搜索科研成果' }).fill('10.1111/cas.14685');
  const publicationLink = page.getByRole('link', { name: publicationTitle });
  await expect(publicationLink).toBeVisible();
  await publicationLink.click();
  await expect(page.getByRole('heading', { level: 1, name: publicationTitle })).toBeVisible();
  await expect(page.getByRole('heading', { level: 2, name: '作者' })).toBeVisible();
  await expect(page.getByText('共同第一作者').first()).toBeVisible();
  await expect(page.getByRole('heading', { level: 2, name: '图谱关系' })).toBeVisible();
  await expect(page.getByText('关系图服务正常')).toBeVisible();

  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/institutions');
  await expect(page.getByRole('heading', { level: 1, name: '机构与学科' })).toBeVisible();
  await page.getByRole('searchbox', { name: '搜索机构与学科' }).fill('Dalian University of Technology');
  const institutionHeading = page.getByRole('heading', { level: 2, name: 'Dalian University of Technology', exact: true });
  await expect(institutionHeading).toBeVisible();
  await institutionHeading.getByRole('link').click();
  await expect(page.getByRole('heading', { level: 1, name: 'Dalian University of Technology', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { level: 2, name: '机构基本信息' })).toBeVisible();
  await expect(page.getByText('关系图服务正常')).toBeVisible();
  const institutionGraph = page.getByLabel('可拖拽的交互关系图');
  const institutionEnvelope = institutionGraph.locator('ellipse[data-cluster-envelope="true"]').first();
  const institutionClusterId = await institutionEnvelope.getAttribute('data-cluster-id');
  if (institutionClusterId === null) throw new Error('机构关系图簇没有可拖拽标识');
  const institutionClusterNode = institutionGraph.locator(`g[data-graph-node="true"].cluster-${institutionClusterId}`).first();
  const institutionClusterBefore = await institutionClusterNode.getAttribute('transform');
  const institutionClusterHandle = institutionGraph.locator(`[data-cluster-handle="true"][data-cluster-id="${institutionClusterId}"]`);
  await institutionClusterHandle.scrollIntoViewIfNeeded();
  const institutionEnvelopeBounds = await institutionClusterHandle.boundingBox();
  if (!institutionEnvelopeBounds) throw new Error('机构关系图簇没有可拖拽区域');
  const institutionGraphBounds = await institutionGraph.boundingBox();
  if (!institutionGraphBounds) throw new Error('机构关系图没有可交互区域');
  const envelopeCenterX = institutionEnvelopeBounds.x + institutionEnvelopeBounds.width / 2;
  const graphCenterX = institutionGraphBounds.x + institutionGraphBounds.width / 2;
  const clusterMoveX = envelopeCenterX > graphCenterX ? -32 : 32;
  await page.mouse.move(institutionEnvelopeBounds.x + institutionEnvelopeBounds.width / 2, institutionEnvelopeBounds.y + institutionEnvelopeBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(institutionEnvelopeBounds.x + institutionEnvelopeBounds.width / 2 + clusterMoveX, institutionEnvelopeBounds.y + institutionEnvelopeBounds.height / 2 + 14);
  await page.mouse.up();
  expect(await institutionClusterNode.getAttribute('transform')).not.toBe(institutionClusterBefore);
  const institutionNode = institutionGraph.locator('g[data-graph-node="true"]:not(.root)').first();
  const dragNode = institutionGraph.locator('g[data-graph-node="true"].root');
  await dragNode.scrollIntoViewIfNeeded();
  const originalTransform = await dragNode.getAttribute('transform');
  const nodeBounds = await dragNode.locator('circle').first().boundingBox();
  if (!nodeBounds) throw new Error('机构关系节点没有可拖拽区域');
  await page.mouse.move(nodeBounds.x + nodeBounds.width / 2, nodeBounds.y + nodeBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(nodeBounds.x + nodeBounds.width / 2 + 50, nodeBounds.y + nodeBounds.height / 2 + 25);
  await page.mouse.up();
  const changedTransform = await dragNode.getAttribute('transform');
  expect(changedTransform).not.toBe(originalTransform);
  await expect(institutionGraph.locator('g.type-organization, g.type-department, g.type-person, g.type-publication').first()).toBeVisible();
  await institutionNode.click();
  const selectedName = (await page.locator('.sg-node-detail h3').textContent())?.trim();
  if (!selectedName) throw new Error('选中节点详情没有名称');
  await page.getByRole('button', { name: '查看关系来源' }).click();
  await expect(page.getByRole('dialog', { name: `${selectedName}的关系来源` })).toBeVisible();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '从当前图中移除' }).click();
  await expect(page.getByText(/不会被删除/)).toBeVisible();
  await page.getByRole('button', { name: '从当前视图移除' }).click();
  await expect(page.getByRole('button', { name: /恢复已移除节点（1）/ })).toBeVisible();
  await page.getByRole('button', { name: /恢复已移除节点（1）/ }).click();
  await page.getByRole('button', { name: '放大图谱区域' }).click();
  await expect(page.getByRole('dialog', { name: '图谱关系放大视图' })).toBeVisible();
  await page.getByRole('button', { name: '退出放大' }).click();
});
